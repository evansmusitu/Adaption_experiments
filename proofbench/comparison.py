"""Paired baseline-vs-candidate numerical reliability comparison.

Operates on *actual external model predictions* with identical test-case IDs.
No model predictions are generated by this module. Confidence intervals use
scenario-group bootstrap rather than falsely treating counterfactual pair
members as independent observations. Exact McNemar test is applied at the
strict-pair success level for the same reason.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import json
from math import comb
from pathlib import Path
import random

from .benchmark import _correct, _read_jsonl, score_predictions


def _mapped(cases: list[dict], predictions: list[dict]) -> dict[str, dict]:
    # Also validates duplicates and unknown IDs.
    score_predictions(cases, predictions)
    return {pred["id"]: pred for pred in predictions}


def _exact_mcnemar(b_only: int, c_only: int) -> float:
    n = b_only + c_only
    if n == 0:
        return 1.0
    small = min(b_only, c_only)
    return min(1.0, 2 * sum(comb(n, i) for i in range(small + 1)) / (2 ** n))


def _percentile(sorted_values: list[float], fraction: float) -> float:
    if not sorted_values:
        return 0.0
    index = (len(sorted_values) - 1) * fraction
    left = int(index)
    right = min(left + 1, len(sorted_values) - 1)
    return sorted_values[left] * (right - index) + sorted_values[right] * (index - left) if left != right else sorted_values[left]


def compare(cases: list[dict], baseline: list[dict], candidate: list[dict], *, resamples: int = 2000) -> dict:
    if not isinstance(resamples, int) or not 1 <= resamples <= 100_000:
        raise ValueError("resamples must be 1..100000")
    before = _mapped(cases, baseline)
    after = _mapped(cases, candidate)
    groups = defaultdict(list)
    for row in cases:
        groups[row["pair_id"]].append(row)
    if not groups or any(len(rows) != 2 or {r["variant"] for r in rows} != {"a", "b"}
                         for rows in groups.values()):
        raise ValueError("All test cases must form complete two-variant scenario pairs")
    report_before = score_predictions(cases, baseline)
    report_after = score_predictions(cases, candidate)
    candidate_only_rows = baseline_only_rows = 0
    candidate_only_pairs = baseline_only_pairs = 0
    group_deltas = []
    for rows in groups.values():
        b_flags = [_correct(r["gold"], before.get(r["id"])) for r in rows]
        c_flags = [_correct(r["gold"], after.get(r["id"])) for r in rows]
        candidate_only_rows += sum(not b and c for b, c in zip(b_flags, c_flags))
        baseline_only_rows += sum(b and not c for b, c in zip(b_flags, c_flags))
        b_pair, c_pair = all(b_flags), all(c_flags)
        candidate_only_pairs += int(c_pair and not b_pair)
        baseline_only_pairs += int(b_pair and not c_pair)
        group_deltas.append((sum(c_flags) - sum(b_flags)) / len(rows))

    # Resample entire scenarios, preserving dependence between the A/B members.
    rng = random.Random(20261120)
    n = len(group_deltas)
    bootstraps = []
    for _ in range(resamples):
        value = sum(group_deltas[rng.randrange(n)] for _ in range(n)) / n
        bootstraps.append(value)
    bootstraps.sort()
    low = round(_percentile(bootstraps, .025), 6)
    high = round(_percentile(bootstraps, .975), 6)

    return {
        "total_cases": len(cases), "paired_scenario_groups": n,
        "baseline_accuracy": report_before["accuracy"],
        "candidate_accuracy": report_after["accuracy"],
        "delta_accuracy": round(report_after["accuracy"] - report_before["accuracy"], 6),
        "baseline_strict_pair_accuracy": report_before["strict_pair_accuracy"],
        "candidate_strict_pair_accuracy": report_after["strict_pair_accuracy"],
        "paired_bootstrap_95": [low, high],
        "bootstrap_resamples": resamples,
        "discordant": {
            "candidate_only_correct": candidate_only_rows,
            "baseline_only_correct": baseline_only_rows,
            "candidate_only_pairs": candidate_only_pairs,
            "baseline_only_pairs": baseline_only_pairs,
        },
        "mcnemar_exact_p": round(_exact_mcnemar(baseline_only_pairs, candidate_only_pairs), 10),
        "inference_note": (
            "McNemar exact test uses whole pairs; bootstrap resamples scenario groups. "
            "Tests assume independent scenario groups. Template-generated development "
            "cases do not establish external generalization; human blind evaluation needed."
        ),
        "data_note": "These are measured predictions only if provided by real model runs; none are synthesized here.",
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cases", required=True, help="JSONL with oracle ground truth")
    ap.add_argument("--baseline", required=True, help="Baseline prediction JSONL")
    ap.add_argument("--candidate", required=True, help="Adapted candidate prediction JSONL")
    ap.add_argument("--output", help="JSON report destination")
    ap.add_argument("--resamples", type=int, default=2000)
    args = ap.parse_args()
    report = compare(
        _read_jsonl(args.cases), _read_jsonl(args.baseline),
        _read_jsonl(args.candidate), resamples=args.resamples,
    )
    rendered = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.output:
        Path(args.output).write_text(rendered, encoding="utf-8")
    print(rendered)


if __name__ == "__main__":
    main()
